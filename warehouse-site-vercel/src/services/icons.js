// أيقونة ولون كل مرحلة وكل نوع حدث (لوحة الإدارة والسجل)
const STATUS_ICONS = { received: 'inbox', preparing: 'package', prepared: 'clipboardCheck', handed_to_courier: 'truck' };

function eventIcon(e) {
  switch (e.type) {
    case 'received': return { name: 'inbox', tone: 'received' };
    case 'modified': return { name: 'refresh', tone: 'info' };
    case 'status_change':
      if (e.to_status === 'preparing') return { name: 'package', tone: 'preparing' };
      if (e.to_status === 'prepared') return { name: 'clipboardCheck', tone: 'prepared' };
      if (e.to_status === 'handed_to_courier') return { name: 'truck', tone: 'handed' };
      return { name: 'activity', tone: 'info' };
    case 'note': return { name: 'message', tone: 'info' };
    case 'shortage': return { name: 'alert', tone: 'danger' };
    case 'shortage_closed': return { name: 'checkCircle', tone: 'prepared' };
    case 'correction': return { name: 'undo', tone: 'preparing' };
    default: return { name: 'activity', tone: 'info' };
  }
}

module.exports = { icon, eventIcon, STATUS_ICONS };
